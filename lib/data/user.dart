class User {
  final String name;
  final String email;
  final String phone;
  final String role;
  final String? weight;
  final String? height;
  final String? age;
  final String? gender;

  User({
    required this.name,
    required this.email,
    required this.phone,
    required this.role,
    required this.weight,
    required this.height,
    required this.age,
    required this.gender,
  });
}

class Trainer {
  final int id;
  final String title;
  final String duration;
  final String imagePath;
  final String email;
  final String description;
  final String specialization;
  final double price;

  Trainer({
    required this.id,
    required this.title,
    required this.duration,
    required this.imagePath,
    required this.email,
    required this.description,
    required this.specialization,
    required this.price,
  });
}
